function normalizeCountry(value: string) {
  return value
    .trim()
    .toLocaleLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "");
}

function getEditDistance(a: string, b: string) {
  const previous = Array.from(
    { length: b.length + 1 },
    (_, index) => index,
  );

  for (let i = 1; i <= a.length; i += 1) {
    let diagonal = previous[0];
    previous[0] = i;

    for (let j = 1; j <= b.length; j += 1) {
      const upper = previous[j];
      const substitutionCost =
        a[i - 1] === b[j - 1] ? 0 : 1;

      previous[j] = Math.min(
        previous[j] + 1,
        previous[j - 1] + 1,
        diagonal + substitutionCost,
      );

      diagonal = upper;
    }
  }

  return previous[b.length];
}

function getCountryScore(country: string, query: string) {
  const normalizedCountry = normalizeCountry(country);
  const normalizedQuery = normalizeCountry(query);

  if (!normalizedQuery) {
    return 0;
  }

  if (normalizedCountry === normalizedQuery) {
    return -1000;
  }

  if (normalizedCountry.startsWith(normalizedQuery)) {
    return -500 + normalizedCountry.length;
  }

  const containsIndex =
    normalizedCountry.indexOf(normalizedQuery);

  if (containsIndex >= 0) {
    return -250 + containsIndex * 10 + normalizedCountry.length;
  }

  const distance = getEditDistance(
    normalizedCountry,
    normalizedQuery,
  );

  return distance * 100 + normalizedCountry.length;
}

export function getCountrySuggestions(
  query: string,
  limit = 6,
) {
  const normalizedQuery = normalizeCountry(query);

  if (!normalizedQuery) {
    return countries.slice(0, limit);
  }

  return [...countries]
    .sort(
      (a, b) =>
        getCountryScore(a, normalizedQuery) -
        getCountryScore(b, normalizedQuery),
    )
    .slice(0, limit);
}

export function isKnownCountry(value: string) {
  const normalizedValue = normalizeCountry(value);

  return countries.some(
    (country) =>
      normalizeCountry(country) === normalizedValue,
  );
}
